def load_source(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def load_public():
    return load_source(Path(__file__).resolve().parents[2] / "tools/schema_validate.py",
                       "schema_public_native_port_target")


def load_native_oracles():
    return load_source(Path(__file__).with_name("native_owner_acceptance.py"),
                       "schema_public_native_port_oracles")


def protocol_row(activation, outcome, status, expected, deadline=False, death=False):
    selected = [row for row in WIRE if row[1:6] == (activation, outcome, status, deadline, death)]
    if not selected or any(row[6] != expected for row in selected):
        raise AssertionError("Public fault input is outside the exact frozen23 rows")
    # a1/e21 have identical wire conditions. Use the first literal name while
    # both original call sites still execute their own fresh isolated child.
    return selected[0][0]


def run_child(case, row):
    """Own an actual isolated TEST process; never infer/pass/rethrow a marker."""
    if row not in tuple(item[0] for item in WIRE) + EXTRA:
        raise AssertionError("Unknown closed public test row")
    with tempfile.TemporaryFile() as stdout, tempfile.TemporaryFile() as stderr:
        child = subprocess.Popen(
            [sys.executable, "-I", "-B", str(Path(__file__).resolve()), "--row", row],
            shell=False, close_fds=True, stdin=subprocess.DEVNULL,
            stdout=stdout, stderr=stderr,
            env={"PATH": "/usr/bin:/bin", "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"})
        try:
            status = child.wait(timeout=30)
        finally:
            if child.poll() is None:
                try:
                    child.kill()
                finally:
                    child.wait(timeout=10)
        stdout.seek(0); stderr.seek(0)
        out, err = stdout.read(262145), stderr.read(262145)
        case.assertLessEqual(len(out), 262144); case.assertLessEqual(len(err), 262144)
        # A failed actual public call remains a failed outer assertion with the
        # full real inner traceback. No stderr-to31 or stderr-to-success mapping.
        case.assertEqual(status, 0, "Public native row " + row + " failed:\n" +
                         err.decode("utf-8", errors="replace"))
        case.assertEqual(out, ("PUBLIC_NATIVE_ROW_OK " + row + "\n").encode("ascii"))


def make_package(directory):
    root = Path(directory)
    values = {
        "s.json": {"$schema": "https://json-schema.org/draft/2020-12/schema", "type": "integer"},
        "v.json": 1,
        "manifest.json": {"profile": "subathon.schema-package.v1",
                          "documents": [{"path": "s.json", "kind": "jsonschema202012"}],
                          "examples": [{"path": "v.json", "schema_document": "s.json", "schema_pointer": ""}]},
    }
    for name, value in values.items():
        (root / name).write_text(json.dumps(value, separators=(",", ":")), encoding="utf-8")
    return root / "manifest.json"


def lookup_native_row(module, name):
    groups = (module.ACTIVATION, module.OUTCOME, module.STATUS, module.SETUP, module.DEADLINE,
              module.PREBIRTH, module.WORK, module.CLEANUP, module.INTERRUPT, module.RESOURCE,
              module.REAPER, module.PACKET)
    found = [row for group in groups for row in group if row[0] == name]
    if len(found) != 1:
        raise AssertionError("Matching native oracle row missing")
    return found[0]


def public_fault(case, name):
    native, target = load_native_oracles(), load_public()
    row = lookup_native_row(native, name)
    with tempfile.TemporaryDirectory(prefix="schema-public-native-") as temporary:
        manifest = make_package(temporary)
        session = native.FaultSession(case, str(Path(__file__).resolve().parents[2] /
            "build/schema-transport-debug/lib/libsubathon_schema_fault_v1.so"), row)
        with session:
            stdout, stderr = io.StringIO(), io.StringIO()
            with mock.patch.object(target, "_load_native_transport", return_value=session.entry,
                                   create=True) as loader, \
                    contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                caught, actual = None, None
                before = time.monotonic()
                try:
                    actual = target.validate_package(str(manifest))
                except KeyboardInterrupt as error:
                    caught = error
                elapsed = time.monotonic() - before
                # The unmodified public API preserves its real missing-feature
                # exception. This helper neither substitutes nor decodes C ints.
                session.assert_evidence()
                case.assertEqual(stdout.getvalue(), "")
                case.assertEqual(stderr.getvalue(), "")
            loader.assert_called_once_with()
            if row[1] == 25:
                case.assertIs(type(caught), KeyboardInterrupt)
                case.assertIsNone(actual)
            else:
                case.assertIsNone(caught)
                expected = {4: "environment_unavailable", 5: "resource_limit", 17: "validation_unavailable"}[row[4]]
                case.assertIs(actual, target.SchemaValidationOutcome(expected))
            if row[1] == 23:
                case.assertGreaterEqual(elapsed, 0); case.assertLess(elapsed, 3)


def descriptor_inventory():
    # An independent whole-table comparison, not a claim about recorded owner
    # FD numbers. listdir's own transient FD is filtered only AFTER it closes.
    names = os.listdir("/proc/self/fd")
    if len(names) > 128:
        raise AssertionError("Public complement FD fixture inventory exceeds bound")
    result = {}
    for name in names:
        if not name.isascii() or not name.isdecimal():
            raise AssertionError("Invalid proc FD name")
        descriptor = int(name)
        try:
            value = os.fstat(descriptor)
        except OSError as error:
            if error.errno != errno.EBADF:
                raise
        else:
            result[descriptor] = (value.st_dev, value.st_ino, value.st_mode,
                                  fcntl.fcntl(descriptor, fcntl.F_GETFD),
                                  fcntl.fcntl(descriptor, fcntl.F_GETFL))
    return result


def no_children(case):
    for flags in (0, 0x20000000):
        with case.assertRaises(ChildProcessError) as absent:
            os.waitid(os.P_ALL, 0, os.WEXITED | os.WNOHANG | os.WNOWAIT | flags)
        case.assertEqual(absent.exception.errno, errno.ECHILD)


@contextlib.contextmanager
def quiet_descriptors():
    """Prepare raw log capture before the measured owned interval; never flush."""
    with contextlib.ExitStack() as stack:
        stdout = stack.enter_context(tempfile.TemporaryFile())
        stderr = stack.enter_context(tempfile.TemporaryFile())
        for descriptor, destination in ((1, stdout), (2, stderr)):
            flags = fcntl.fcntl(descriptor, fcntl.F_GETFD)
            saved = os.dup(descriptor)
            stack.callback(os.close, saved)
            stack.callback(os.dup2, saved, descriptor, inheritable=not bool(flags & fcntl.FD_CLOEXEC))
            os.dup2(destination.fileno(), descriptor)
        yield stdout, stderr


def postreturn_negative(case, name):
    """REAL production0 then only a negative Python decode-site fault."""
    native, target = load_native_oracles(), load_public()
    refusal = (MemoryError("POST_NATIVE_SPAWN_ALLOCATION_REFUSAL") if name == "postreturn-memory"
               else KeyboardInterrupt("owned descriptor close cancellation" if name == "cancel-identity"
                                      else "native constructor cancellation"))
    calls = []
    with tempfile.TemporaryDirectory(prefix="schema-public-postreturn-") as temporary:
        manifest = make_package(temporary)
        before_handler = signal.getsignal(signal.SIGINT)
        before_mask = signal.pthread_sigmask(signal.SIG_BLOCK, [])
        stdout, stderr = io.StringIO(), io.StringIO()

        def decode_after_return(raw):
            if type(raw) is int and raw == 31:
                raise native.SchemaTransportNotImplemented()  # Actual raw31, never fake success.
            case.assertIs(type(raw), int)
            case.assertEqual(raw, 0)  # Real production worker/SDK positive, not raw5 masking conversion.
            case.assertEqual(descriptor_inventory(), before_fds)
            no_children(case)
            case.assertIs(signal.getsignal(signal.SIGINT), before_handler)
            case.assertEqual(signal.pthread_sigmask(signal.SIG_BLOCK, []), before_mask)
            calls.append(raw)
            raise refusal

        with quiet_descriptors() as (raw_stdout, raw_stderr):
            # All capture descriptors exist before this baseline and before C.
            before_fds = descriptor_inventory()
            with mock.patch.object(target, "_decode_native_result", side_effect=decode_after_return,
                                   create=True) as decoder, \
                    contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                caught, actual = None, None
                try:
                    actual = target.validate_package(str(manifest))
                except KeyboardInterrupt as error:
                    caught = error
            decoder.assert_called_once_with(0)
            case.assertEqual(calls, [0])
            if isinstance(refusal, KeyboardInterrupt):
                case.assertIs(caught, refusal)
                case.assertIsNone(actual)
            else:
                case.assertIsNone(caught)
                case.assertIs(actual, target.SchemaValidationOutcome.resource_limit)
            case.assertEqual(descriptor_inventory(), before_fds)
            no_children(case)
            case.assertEqual(stdout.getvalue(), ""); case.assertEqual(stderr.getvalue(), "")
            case.assertEqual(os.fstat(raw_stdout.fileno()).st_size, 0)
            case.assertEqual(os.fstat(raw_stderr.fileno()).st_size, 0)


def main():
    names = tuple(row[0] for row in WIRE) + EXTRA
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--row", required=True, choices=names)
    selected = parser.parse_args().row

    def probe():
        case = unittest.TestCase()
        if selected in ("cancel-identity", "spawn-identity", "postreturn-memory"):
            postreturn_negative(case, selected)
        else:
            public_fault(case, selected)

    result = unittest.TextTestRunner(verbosity=2).run(unittest.TestSuite([unittest.FunctionTestCase(probe)]))
    if result.testsRun != 1:
        raise SystemExit(2)
    if result.wasSuccessful():
        # TEST-driver completion only, after every independent oracle. A native
        # premature exit0 cannot masquerade as a completed inner test.
        sys.stdout.write("PUBLIC_NATIVE_ROW_OK " + selected + "\n")
    raise SystemExit(0 if result.wasSuccessful() else 1)


if __name__ == "__main__":
    main()
